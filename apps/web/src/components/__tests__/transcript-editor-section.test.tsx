describe("TranscriptEditorSection — remove existing transcript", () => {
  afterEach(() => {
    vi.unstubAllGlobals();
  });

  it("shows 'Remove current transcript' button when transcript exists", () => {
    render(
      <TranscriptEditorSection
        currentTranscription={EXISTING_TRANSCRIPT}
        onTranscriptChange={vi.fn()}
      />,
    );
    expect(
      screen.getByRole("button", { name: "Remove current transcript" }),
    ).toBeInTheDocument();
  });

  it("does not show 'Remove' button when no transcript exists", () => {
    render(
      <TranscriptEditorSection
        currentTranscription={null}
        onTranscriptChange={vi.fn()}
      />,
    );
    expect(
      screen.queryByRole("button", { name: "Remove current transcript" }),
    ).not.toBeInTheDocument();
  });

  it("calls onTranscriptChange(null) when Remove is clicked", async () => {
    const user = userEvent.setup();
    const onTranscriptChange = vi.fn();
    render(
      <TranscriptEditorSection
        currentTranscription={EXISTING_TRANSCRIPT}
        onTranscriptChange={onTranscriptChange}
      />,
    );

    await user.click(
      screen.getByRole("button", { name: "Remove current transcript" }),
    );

    expect(onTranscriptChange).toHaveBeenCalledOnce();
    expect(onTranscriptChange).toHaveBeenCalledWith(null);
  });
});

