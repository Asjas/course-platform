describe("TranscriptPanel — search", () => {
  it("renders a Search toggle button", async () => {
    render(<TranscriptPanel transcription={VALID_TRANSCRIPT} />);
    await screen.findByRole("region", { name: "Lesson transcript" });
    expect(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    ).toBeInTheDocument();
  });

  it("opens the search bar when Search is clicked", async () => {
    const user = userEvent.setup();
    render(<TranscriptPanel transcription={VALID_TRANSCRIPT} />);
    await screen.findByRole("region", { name: "Lesson transcript" });

    await user.click(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    );

    expect(
      screen.getByRole("searchbox", { name: "Transcript search query" }),
    ).toBeInTheDocument();
  });

  it("shows match counter after typing a search query", async () => {
    const user = userEvent.setup();
    render(<TranscriptPanel transcription={VALID_TRANSCRIPT} />);
    await screen.findByRole("region", { name: "Lesson transcript" });

    await user.click(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    );
    const input = screen.getByRole("searchbox", {
      name: "Transcript search query",
    });
    // "Fastify" appears in cues c1 and c2
    await user.type(input, "Fastify");

    await waitFor(() => {
      expect(screen.getByText(/1 \/ 2/)).toBeInTheDocument();
    });
  });

  it("shows '0 results' when query has no matches", async () => {
    const user = userEvent.setup();
    render(<TranscriptPanel transcription={VALID_TRANSCRIPT} />);
    await screen.findByRole("region", { name: "Lesson transcript" });

    await user.click(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    );
    await user.type(
      screen.getByRole("searchbox", { name: "Transcript search query" }),
      "xyzxyz",
    );

    await waitFor(() => {
      expect(screen.getByText("0 results")).toBeInTheDocument();
    });
  });

  it("advances to next match on Next button click", async () => {
    const user = userEvent.setup();
    render(<TranscriptPanel transcription={VALID_TRANSCRIPT} />);
    await screen.findByRole("region", { name: "Lesson transcript" });

    await user.click(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    );
    await user.type(
      screen.getByRole("searchbox", { name: "Transcript search query" }),
      "Fastify",
    );

    // Initially at 1/2
    await waitFor(() => expect(screen.getByText(/1 \/ 2/)).toBeInTheDocument());

    await user.click(screen.getByRole("button", { name: "Next match" }));
    await waitFor(() => expect(screen.getByText(/2 \/ 2/)).toBeInTheDocument());
  });

  it("goes to previous match on Prev button click", async () => {
    const user = userEvent.setup();
    render(<TranscriptPanel transcription={VALID_TRANSCRIPT} />);
    await screen.findByRole("region", { name: "Lesson transcript" });

    await user.click(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    );
    await user.type(
      screen.getByRole("searchbox", { name: "Transcript search query" }),
      "Fastify",
    );

    // advance to 2/2 first
    await waitFor(() => expect(screen.getByText(/1 \/ 2/)).toBeInTheDocument());
    await user.click(screen.getByRole("button", { name: "Next match" }));
    await waitFor(() => expect(screen.getByText(/2 \/ 2/)).toBeInTheDocument());

    // go back
    await user.click(screen.getByRole("button", { name: "Previous match" }));
    await waitFor(() => expect(screen.getByText(/1 \/ 2/)).toBeInTheDocument());
  });

  it("advances with Enter key and goes back with Shift+Enter", async () => {
    const user = userEvent.setup();
    render(<TranscriptPanel transcription={VALID_TRANSCRIPT} />);
    await screen.findByRole("region", { name: "Lesson transcript" });

    await user.click(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    );
    const input = screen.getByRole("searchbox", {
      name: "Transcript search query",
    });
    await user.type(input, "Fastify");
    await waitFor(() => expect(screen.getByText(/1 \/ 2/)).toBeInTheDocument());

    // Enter → next match
    await user.keyboard("{Enter}");
    await waitFor(() => expect(screen.getByText(/2 \/ 2/)).toBeInTheDocument());

    // Shift+Enter → previous match
    await user.keyboard("{Shift>}{Enter}{/Shift}");
    await waitFor(() => expect(screen.getByText(/1 \/ 2/)).toBeInTheDocument());
  });

  it("closes search bar on Escape key", async () => {
    const user = userEvent.setup();
    render(<TranscriptPanel transcription={VALID_TRANSCRIPT} />);
    await screen.findByRole("region", { name: "Lesson transcript" });

    await user.click(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    );
    // Verify the search box opened, then close it with Escape
    expect(
      screen.getByRole("searchbox", { name: "Transcript search query" }),
    ).toBeInTheDocument();

    await user.keyboard("{Escape}");

    await waitFor(() => {
      expect(
        screen.queryByRole("searchbox", { name: "Transcript search query" }),
      ).not.toBeInTheDocument();
    });
  });

  it("closes search bar on Close search button click", async () => {
    const user = userEvent.setup();
    render(<TranscriptPanel transcription={VALID_TRANSCRIPT} />);
    await screen.findByRole("region", { name: "Lesson transcript" });

    await user.click(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    );
    expect(
      screen.getByRole("searchbox", { name: "Transcript search query" }),
    ).toBeInTheDocument();

    await user.click(screen.getByRole("button", { name: "Close search" }));

    await waitFor(() => {
      expect(
        screen.queryByRole("searchbox", { name: "Transcript search query" }),
      ).not.toBeInTheDocument();
    });
  });

  it("prev/next buttons are disabled when there are no matches", async () => {
    const user = userEvent.setup();
    render(<TranscriptPanel transcription={VALID_TRANSCRIPT} />);
    await screen.findByRole("region", { name: "Lesson transcript" });

    await user.click(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    );

    // No query yet — match count is 0
    expect(
      screen.getByRole("button", { name: "Previous match" }),
    ).toBeDisabled();
    expect(screen.getByRole("button", { name: "Next match" })).toBeDisabled();
  });

  it("calls onSeek when the Next button advances to a match with onSeek provided", async () => {
    const user = userEvent.setup();
    const onSeek = vi.fn();
    render(
      <TranscriptPanel
        transcription={VALID_TRANSCRIPT}
        onSeek={onSeek}
      />,
    );
    await screen.findByRole("region", { name: "Lesson transcript" });

    await user.click(
      screen.getByRole("button", { name: "Toggle transcript search" }),
    );
    await user.type(
      screen.getByRole("searchbox", { name: "Transcript search query" }),
      "Fastify",
    );
    await waitFor(() => expect(screen.getByText(/1 \/ 2/)).toBeInTheDocument());

    await user.click(screen.getByRole("button", { name: "Next match" }));

    // Second "Fastify" cue starts at 8000 ms → 8s
    await waitFor(() => {
      expect(onSeek).toHaveBeenCalledWith(8);
    });
  });
});
