/**
 * Search cues for a case-insensitive substring match.
 *
 * Returns all matching cues with their index in the source cue array.
 */
export function searchTranscript(
  transcript: TranscriptData,
  query: string,
): TranscriptSearchResult {
  const trimmedQuery = query.trim();
  if (!trimmedQuery) return { query, matches: [] };

  const lower = trimmedQuery.toLowerCase();
  const matches: TranscriptSearchMatch[] = [];

  for (let i = 0; i < transcript.cues.length; i++) {
    const cue = transcript.cues[i];
    const idx = cue.text.toLowerCase().indexOf(lower);
    if (idx !== -1) {
      matches.push({ cueIndex: i, cue, matchIndex: idx });
    }
  }

  return { query: trimmedQuery, matches };
}

// ---------------------------------------------------------------------------
// Zod validation schema
// ---------------------------------------------------------------------------

export const transcriptCueSchema = z.object({
  id: z.string(),
  startMs: z.number().int().min(0),
  endMs: z.number().int().min(0),
  text: z.string(),
  speaker: z.string().optional(),
});

export const transcriptDataSchema = z.object({
  version: z.literal(1),
  language: z.string().min(1),
  source: z.enum(["manual", "auto"]),
  sourceProvider: z.string().optional(),
  sourceTrackId: z.string().optional(),
  lastFetchedAt: z.string().datetime({ offset: true }).optional(),
  isAutoGenerated: z.boolean(),
  cueCount: z.number().int().min(0),
  durationMs: z.number().int().min(0),
  cues: z.array(transcriptCueSchema),
});

/**
 * Validate a raw JSON value as a `TranscriptData` payload.
 * Returns the parsed payload on success, `null` on failure.
 */
export function validateTranscriptData(raw: unknown): TranscriptData | null {
  const result = transcriptDataSchema.safeParse(raw);
  return result.success ? result.data : null;
}

// ---------------------------------------------------------------------------
// Publish eligibility
// ---------------------------------------------------------------------------

/**
 * Reasons why a transcript is not publish-eligible.
 */
export type TranscriptIneligibleReason =
  | "missing"
  | "invalid_schema"
  | "no_cues";

/**
 * Result of checking transcript publish eligibility.
 */
export type TranscriptEligibility =
  | { eligible: true }
  | { eligible: false; reason: TranscriptIneligibleReason };

/**
 * Determine whether a lesson transcript is ready for publishing.
 *
 * Rules (from blueprint):
 *   - Non-video lessons are always eligible (pass `hasVideo = false`).
 *   - Video lessons with a valid transcript containing ≥1 cue are eligible.
 *   - Empty or missing transcripts block publish.
 */
export function checkTranscriptEligibility(
  transcription: unknown,
  hasVideo: boolean,
): TranscriptEligibility {
  if (!hasVideo) return { eligible: true };

  if (transcription === null || transcription === undefined) {
    return { eligible: false, reason: "missing" };
  }

  const parsed = validateTranscriptData(transcription);
  if (!parsed) {
    return { eligible: false, reason: "invalid_schema" };
  }

  if (parsed.cues.length === 0) {
    return { eligible: false, reason: "no_cues" };
  }

  return { eligible: true };
}

