/**
 * Format milliseconds as a human-readable timestamp string "M:SS" or "H:MM:SS".
 */
export function formatCueTime(ms: number): string {
  const totalSeconds = Math.floor(ms / 1000);
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;

  const ss = seconds.toString().padStart(2, "0");
  if (hours > 0) {
    const mm = minutes.toString().padStart(2, "0");
    return `${hours}:${mm}:${ss}`;
  }
  return `${minutes}:${ss}`;
}

/**
 * Find the index of the active cue at a given playback position.
 * Returns -1 when no cue spans the current time.
 */
export function findActiveCueIndex(
  cues: TranscriptCue[],
  positionMs: number,
): number {
  for (let i = 0; i < cues.length; i++) {
    if (positionMs >= cues[i].startMs && positionMs < cues[i].endMs) {
      return i;
    }
  }
  return -1;
}
